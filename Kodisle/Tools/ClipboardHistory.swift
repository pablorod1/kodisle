import AppKit
import Observation

/// In-memory clipboard history. Nothing is ever written to disk; quitting Kodisle clears it.
///
/// - Items marked concealed/transient by password managers are never recorded.
/// - Text that looks like a secret (API keys, tokens, JWTs, private keys) is shown masked
///   and dropped after two minutes.
@MainActor @Observable
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    private(set) var items: [ClipItem] = []
    var paused = false
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    private static let limit = 60
    private static let secretLifetime: TimeInterval = 120

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type", "com.apple.is-remote-clipboard-transient",
    ]

    private static let secretPatterns: [String] = [
        #"^(gh[pousr]_|github_pat_)[A-Za-z0-9_]{20,}"#,           // GitHub
        #"^sk-(ant-|proj-)?[A-Za-z0-9_\-]{20,}"#,                  // Anthropic / OpenAI
        #"^(AKIA|ASIA)[0-9A-Z]{16}$"#,                              // AWS
        #"^xox[abprs]-[A-Za-z0-9-]{10,}"#,                          // Slack
        #"^eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\."#,           // JWT
        #"-----BEGIN [A-Z ]*PRIVATE KEY-----"#,                     // private keys
        #"^(sk|rk|pk)_(live|test)_[A-Za-z0-9]{16,}"#,               // Stripe
        #"^AIza[0-9A-Za-z_\-]{35}$"#,                               // Google API
        #"^[A-Za-z0-9+/_\-]{40,}={0,2}$"#,                          // long opaque token
        #"(?i)(password|passwd|secret|token|api[_-]?key)\s*[=:]\s*\S{8,}"#,
    ]

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 1.0, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let pb = NSPasteboard.general
        let now = Date()
        items.removeAll { $0.isSecret && now.timeIntervalSince($0.date) > Self.secretLifetime }
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !paused else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes), let text = pb.string(forType: .string) else { return }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, trimmed.count < 50_000 else { return }
        items.removeAll { $0.text == text }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        items.insert(ClipItem(text: text, date: now, app: app, isSecret: Self.looksSecret(trimmed)), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    static func looksSecret(_ text: String) -> Bool {
        guard !text.contains(" ") || text.contains("PRIVATE KEY") || text.contains("=") || text.contains(":") else { return false }
        return secretPatterns.contains { text.range(of: $0, options: .regularExpression) != nil }
    }

    func copy(_ item: ClipItem) {
        Clipboard.copy(item.text, sensitive: item.isSecret)
        lastChange = NSPasteboard.general.changeCount
        if let index = items.firstIndex(of: item) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
        }
    }

    func remove(_ item: ClipItem) { items.removeAll { $0.id == item.id } }
    func clear() { items.removeAll() }
}
